#!/usr/bin/env python3
"""Regenerate docs/contract-errors.md from the ContractError enum.

The enum in contracts/ttl_vault/src/lib.rs is the source of truth. Each variant
becomes one row; a `///` doc comment directly above a variant becomes its
description. CI runs this script and fails if the committed doc drifts.
"""

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "contracts" / "ttl_vault" / "src" / "lib.rs"
OUTPUT = ROOT / "docs" / "contract-errors.md"

ENUM_START = "pub enum ContractError {"
VARIANT_RE = re.compile(r"^\s*(?P<name>[A-Za-z]\w*)\s*=\s*(?P<code>\d+),\s*(//.*)?$")

HEADER = """# Contract Error Codes

This document is generated from the `ContractError` enum in the smart contract source.
Do not edit this file by hand. Regenerate it with:

```sh
python3 scripts/generate_contract_error_docs.py
```

CI runs the same generator and fails if the committed table drifts from the enum.

| Code | Variant | Description |
| --- | --- | --- |
"""


def parse_variants(lines):
    variants = []
    doc = []
    inside = False
    for line in lines:
        stripped = line.strip()
        if not inside:
            inside = stripped == ENUM_START
            continue
        if stripped == "}":
            break
        if stripped.startswith("///"):
            doc.append(stripped[3:].strip())
            continue
        match = VARIANT_RE.match(line)
        if match:
            variants.append((int(match["code"]), match["name"], " ".join(doc)))
        doc = []
    if not variants:
        raise SystemExit(f"no variants found in {SOURCE}")
    return variants


def render(variants):
    rows = [f"| {code} | `{name}` | {description} |" for code, name, description in variants]
    return HEADER + "\n".join(rows) + "\n"


def main():
    variants = parse_variants(SOURCE.read_text().splitlines())
    OUTPUT.write_text(render(variants))


if __name__ == "__main__":
    main()
